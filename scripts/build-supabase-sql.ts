/**
 * Builds supabase/setup.sql: one file to paste into Supabase → SQL Editor.
 * Creates the vapp_app role, applies every migration in order, and records them in
 * schema_migrations (with the same checksums `npm run db:migrate` uses), so later
 * migrations can run either way.  Re-run this script whenever a migration is added.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";

const files = readdirSync("db/migrations").filter((f) => f.endsWith(".sql")).sort();
let out = `-- ============================================================================
-- V.app — Supabase setup (generated by scripts/build-supabase-sql.ts — do not edit)
-- 1. Replace CHANGE_ME_APP_DB_PASSWORD below with a long random password.
--    (Letters and numbers only — avoid quotes and @ : / ? # so it works in a URL.)
-- 2. Paste this whole file into Supabase → SQL Editor → Run.
-- Safe to run once on an empty project. Includes migrations: ${files.join(", ")}
-- ============================================================================

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'vapp_app') then
    create role vapp_app login password 'CHANGE_ME_APP_DB_PASSWORD' nosuperuser nocreatedb nocreaterole noinherit;
  else
    alter role vapp_app with login password 'CHANGE_ME_APP_DB_PASSWORD';
  end if;
end $$;

create table if not exists schema_migrations (name text primary key, checksum text not null, applied_at timestamptz not null default now());
`;
for (const f of files) {
  const body = readFileSync(`db/migrations/${f}`, "utf8");
  const sum = createHash("sha256").update(body).digest("hex");
  out += `\n-- ─── ${f} ${"─".repeat(Math.max(0, 70 - f.length))}\n${body}\ninsert into schema_migrations (name, checksum) values ('${f}', '${sum}') on conflict (name) do nothing;\n`;
}
out += `\nselect 'V.app database ready — ' || count(*) || ' migrations recorded' as status from schema_migrations;\n`;
mkdirSync("supabase", { recursive: true });
writeFileSync("supabase/setup.sql", out);
console.log(`supabase/setup.sql written (${files.length} migrations)`);
